// HMDA LAR export service (task-042 — REQ-076 / DATA-003 / NFR-015, RFP
// §4.9.4 / §5.3, ASM-003 / ASM-005 / ASM-010, WALK-005, SEC-14, INV-037).
//
// Produces the FFIEC pipe-delimited LAR file for a Supervisor-selected
// calendar year: one transmittal-sheet header record (record id 1) + one LAR
// record (record id 2, 110 fields) per application with a reportable action
// in the year. The field order and every code table live in
// hmda-lar-mapping.ts (the ASM-010 machine-readable mapping — this builder
// and the evidence suite both read it).
//
// SEC-14 / WALK-005: records are generated by STREAMING QUERY — a keyset
// cursor over Application (batches <= 1000) with per-batch bounded loads for
// checks and denial records; the full set is never held in memory. Every
// SELECT issued here carries a LIMIT (take) or is an aggregate COUNT — this
// is query-log verified by the evidence suite.
//
// Reportable membership + action mapping (ASM-005 / AC-50, documented):
//   - approved, borrower_notified+outcome=approved  -> 2 (approved but not
//     accepted; loans are never originated in-system), action date decidedAt
//   - declined_by_borrower                          -> 2 (ASM-005), action
//     date stateEnteredAt (the borrower's decline moment)
//   - denied, borrower_notified+outcome=denied      -> 3, action date decidedAt
//   - withdrawn                                     -> 4, action date
//     stateEnteredAt (the withdrawal moment; no decision exists)
//   - every other state is IN-FLIGHT and EXCLUDED; "file closed for
//     incompleteness" (5) is unused (no closure mechanism exists).
// Calendar-year membership is evaluated on the action date in the CONFIGURED
// company time zone (INV-045, `company.timeZone`, default America/New_York):
// the year window is
// [Jan 1 00:00 local, next Jan 1 00:00 local), computed from the zone's real
// UTC offset at each boundary (never a hardcoded offset).
//
// INV-037 (pipe-delimiter survival): free-text values (street, city,
// ethnicity/race free-forms, denial free-form) are sanitized by replacing the
// field delimiter "|" with "/" and CR/LF with spaces — the value survives
// legibly and the file stays field-aligned. Documented here and in the
// mapping artifact.

