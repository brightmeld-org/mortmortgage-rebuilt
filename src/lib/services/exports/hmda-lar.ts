/**
 * Bounded per-batch load of a related table: keyset cursor on id with the
 * batch size as LIMIT so every emitted SELECT is cursor/LIMIT-bounded
 * (SEC-14 evidence checks the query log).
 */
async function loadAllBatched<T extends { id: string }>(
  fetchPage: (cursorId: string | null) => Promise<T[]>,
): Promise<T[]> {
  const rows: T[] = [];
  let cursorId: string | null = null;
  for (;;) {
    const page = await fetchPage(cursorId);
    rows.push(...page);
    if (page.length === 0) break;
    cursorId = page[page.length - 1]!.id;
  }
  return rows;
}

/**
 * Generate the complete pipe-delimited LAR file as an async stream of lines
 * (each terminated with "\n"): transmittal-sheet header first, then one
 * 110-field record per reportable application, streamed by keyset cursor.
 */
export async function* generateLarFile(
  year: number,
  cfg: HmdaLarConfig,
  db: PrismaClient = prisma,
  opts: LarStreamOptions = {},
): AsyncGenerator<string> {
  const batchSize = Math.max(1, Math.min(opts.batchSize ?? DEFAULT_BATCH_SIZE, 1000));
  const where = reportableWhere(year, cfg.timeZone);

  // Transmittal sheet (15 fields — hmda-lar-mapping.ts TS_FIELDS).
  const total = await db.application.count({ where });
  const tsFields = [
    "1",
    "MortMortgage",
    String(year),
    "4",
    "NA",
    "NA",
    "NA",
    "NA",
    "NA",
    "NA",
    "NA",
    cfg.agencyCode,
    String(total),
    "NA",
    cfg.lei,
  ];
  if (tsFields.length !== TS_FIELD_COUNT) {
    throw new Error(`transmittal sheet produced ${tsFields.length} fields, expected ${TS_FIELD_COUNT}`);
  }
  yield `${tsFields.join("|")}\n`;

  let cursorId: string | null = null;
  for (;;) {
    const apps: LarAppRow[] = await db.application.findMany({
      where,
      orderBy: { id: "asc" },
      take: batchSize,
      cursor: cursorId === null ? undefined : { id: cursorId },
      skip: cursorId === null ? 0 : 1,
      select: LAR_APP_SELECT,
    });
    if (apps.length === 0) break;
    cursorId = apps[apps.length - 1]!.id;
    const ids = apps.map((a) => a.id);

    // Borrower rows for the batch (own LIMITed cursor pages — SEC-14; at
    // most 2 per application, INV-035).
    const borrowerRows: BorrowerRow[] = await loadAllBatched((cur) =>
      db.borrower.findMany({
        where: { applicationId: { in: ids } },
        orderBy: { id: "asc" },
        take: batchSize,
        cursor: cur === null ? undefined : { id: cur },
        skip: cur === null ? 0 : 1,
        select: {
          id: true,
          applicationId: true,
          ordinal: true,
          dateOfBirthCiphertext: true,
          dateOfBirthKeyId: true,
          demographics: true,
          employments: true,
          otherIncome: true,
        },
      }),
    );
    const borrowersByApp = new Map<string, BorrowerRow[]>();
    for (const row of borrowerRows) {
      const list = borrowersByApp.get(row.applicationId) ?? [];
      list.push(row);
      borrowersByApp.set(row.applicationId, list);
    }
    for (const list of borrowersByApp.values()) list.sort((a, b) => a.ordinal - b.ordinal);

    // Latest completed non-superseded credit / aus / avm per application.
    const checkRows = await loadAllBatched((cur) =>
      db.underwritingResult.findMany({
        where: {
          applicationId: { in: ids },
          checkType: { in: ["credit", "aus", "avm"] },
          status: "completed",
          supersededById: null,
        },
        orderBy: { id: "asc" },
        take: batchSize,
        ...(cur ? { cursor: { id: cur }, skip: 1 } : {}),
        select: {
          id: true,
          applicationId: true,
          checkType: true,
          isStale: true,
          completedAt: true,
          result: true,
        },
      }),
    );
    // Deny approval records (denial reasons, WF-024/VR-087).
    const denialRows = await loadAllBatched((cur) =>
      db.approvalRecord.findMany({
        where: { applicationId: { in: ids }, decision: "deny" },
        orderBy: { id: "asc" },
        take: batchSize,
        ...(cur ? { cursor: { id: cur }, skip: 1 } : {}),
        select: {
          id: true,
          applicationId: true,
          denialReasons: true,
          denialReasonOtherText: true,
          createdAt: true,
        },
      }),
    );

    const latestCheck = new Map<string, CheckRow>();
    for (const row of checkRows) {
      const key = `${row.applicationId}:${row.checkType}`;
      const prev = latestCheck.get(key);
      if (!prev || (row.completedAt?.getTime() ?? 0) > (prev.completedAt?.getTime() ?? 0)) {
        latestCheck.set(key, row);
      }
    }
    const latestDenial = new Map<string, DenialRow>();
    for (const row of denialRows) {
      const prev = latestDenial.get(row.applicationId);
      if (!prev || row.createdAt.getTime() > prev.createdAt.getTime()) {
        latestDenial.set(row.applicationId, row);
      }
    }

    for (const app of apps) {
      const fields = buildLarRecord(
        app,
        borrowersByApp.get(app.id) ?? [],
        cfg,
        latestCheck.get(`${app.id}:credit`) ?? null,
        latestCheck.get(`${app.id}:aus`) ?? null,
        latestCheck.get(`${app.id}:avm`) ?? null,
        latestDenial.get(app.id) ?? null,
      );
      if (fields.length !== LAR_FIELD_COUNT) {
        throw new Error(`LAR record produced ${fields.length} fields, expected ${LAR_FIELD_COUNT}`);
      }
      yield `${fields.join("|")}\n`;
    }
  }
}

