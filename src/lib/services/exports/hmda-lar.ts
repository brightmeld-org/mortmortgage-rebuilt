/** Validate and parse `?year=YYYY`. Throws HttpProblem 400 with details[]. */
export function parseLarYear(request: Request): number {
  const url = new URL(request.url);
  const raw = url.searchParams.get("year");
  const details: string[] = [];
  if (raw === null || raw.trim() === "") {
    details.push("year: required — a four-digit calendar year (?year=YYYY)");
  } else if (!/^\d{4}$/.test(raw.trim())) {
    details.push("year: must be a four-digit calendar year (YYYY)");
  } else {
    const year = Number(raw.trim());
    if (year < 1900 || year > 2199) {
      details.push("year: must be a plausible calendar year (1900-2199)");
    } else {
      return year;
    }
  }
  throw new HttpProblem(400, ERROR_CODES.validationError, "Request validation failed", {
    details,
  });
}

