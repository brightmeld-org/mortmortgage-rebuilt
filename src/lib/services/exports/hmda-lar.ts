/**
 * Read hmda.lei + hmda.agencyCode via the config service (never hardcoded).
 * Throws HttpProblem 409 while EITHER is blank (§4.6.11 defaults are blank).
 */
export async function requireHmdaConfig(): Promise<HmdaLarConfig> {
  const [lei, agencyCode, timeZone] = await Promise.all([
    getStringSetting("hmda.lei"),
    getStringSetting("hmda.agencyCode"),
    getCompanyTimeZone(),
  ]);
  const missing: string[] = [];
  if (lei.trim() === "") missing.push("HMDA LEI (hmda.lei)");
  if (agencyCode.trim() === "") missing.push("HMDA agency code (hmda.agencyCode)");
  if (missing.length > 0) {
    throw new HttpProblem(
      409,
      ERROR_CODES.conflict,
      `HMDA LAR export is blocked until the following configuration is set: ${missing.join(", ")}`,
    );
  }
  return { lei: lei.trim(), agencyCode: agencyCode.trim(), timeZone };
}

