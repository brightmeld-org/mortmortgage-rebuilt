// Calendar-year window (configured company zone — INV-045)
// ---------------------------------------------------------------------------

const PARTS_FORMATS = new Map<string, Intl.DateTimeFormat>();

function partsFormat(timeZone: string): Intl.DateTimeFormat {
  let fmt = PARTS_FORMATS.get(timeZone);
  if (!fmt) {
    fmt = new Intl.DateTimeFormat("en-US", {
      timeZone,
      hourCycle: "h23",
      year: "numeric",
      month: "2-digit",
      day: "2-digit",
      hour: "2-digit",
      minute: "2-digit",
      second: "2-digit",
    });
    PARTS_FORMATS.set(timeZone, fmt);
  }
  return fmt;
}

function zoneParts(instant: Date, timeZone: string): Record<string, number> {
  const out: Record<string, number> = {};
  for (const part of partsFormat(timeZone).formatToParts(instant)) {
    if (part.type !== "literal") out[part.type] = Number(part.value);
  }
  return out;
}

/** The zone's UTC offset (ms) at a given instant. */
function zoneOffsetMs(instant: Date, timeZone: string): number {
  const p = zoneParts(instant, timeZone);
  const asIfUtc = Date.UTC(p.year!, p.month! - 1, p.day!, p.hour!, p.minute!, p.second!);
  return asIfUtc - Math.floor(instant.getTime() / 1000) * 1000;
}

/** UTC instant of local midnight on Jan 1 of `year` in `timeZone` (two-pass, DST-safe). */
function zonedYearStartUtc(year: number, timeZone: string): Date {
  const naive = Date.UTC(year, 0, 1, 0, 0, 0);
  const first = new Date(naive - zoneOffsetMs(new Date(naive), timeZone));
  return new Date(naive - zoneOffsetMs(first, timeZone));
}

/** UTC instants of [Jan 1 00:00 local, next Jan 1 00:00 local) in the company zone. */
export function larYearWindowUtc(year: number, timeZone: string): { start: Date; end: Date } {
  return {
    start: zonedYearStartUtc(year, timeZone),
    end: zonedYearStartUtc(year + 1, timeZone),
  };
}

/** Calendar-date parts of an instant in the company time zone. */
export function etDateParts(
  instant: Date,
  timeZone: string,
): { year: number; month: number; day: number } {
  const p = zoneParts(instant, timeZone);
  return { year: p.year!, month: p.month!, day: p.day! };
}

/** YYYYMMDD (company time zone) for the LAR date fields. */
function larDate(instant: Date | null, timeZone: string): string {
  if (!instant) return "NA";
  const { year, month, day } = etDateParts(instant, timeZone);
  return `${year}${String(month).padStart(2, "0")}${String(day).padStart(2, "0")}`;
}

// ---------------------------------------------------------------------------
// ULI (LEI + applicationNumber + ISO 7064 MOD 97-10 check digits)
// ---------------------------------------------------------------------------

/** MOD 97 of the base-10 expansion where A=10..Z=35 (ISO/IEC 7064 mapping). */
export function uliMod97(value: string): number {
  let rem = 0;
  for (const ch of value.toUpperCase()) {
    let mapped: number;
    if (ch >= "0" && ch <= "9") mapped = ch.charCodeAt(0) - 48;
    else if (ch >= "A" && ch <= "Z") mapped = ch.charCodeAt(0) - 55; // A=10..Z=35
    else throw new Error(`ULI characters must be alphanumeric, got "${ch}"`);
    rem = (rem * (mapped > 9 ? 100 : 10) + mapped) % 97;
  }
  return rem;
}

/** Two check digits per ISO/IEC 7064 MOD 97-10 (98 - mod97(base + "00")). */
export function uliCheckDigits(base: string): string {
  const rem = uliMod97(`${base}00`);
  return String(98 - rem).padStart(2, "0");
}

/**
 * ULI = LEI + applicationNumber (non-alphanumerics stripped: MM-YYYY-NNNNNN
 * becomes MMYYYYNNNNNN) + 2 check digits. A valid ULI satisfies mod97 == 1.
 */
export function buildUli(lei: string, applicationNumber: string): string {
  const loanId = applicationNumber.replace(/[^0-9A-Za-z]/g, "").toUpperCase();
  const base = `${lei.toUpperCase()}${loanId}`;
  return `${base}${uliCheckDigits(base)}`;
}

// ---------------------------------------------------------------------------
// Age at application date (REQ-076: never the export date)
// ---------------------------------------------------------------------------

/**
 * Whole years completed between an ISO DOB (YYYY-MM-DD) and an application
 * calendar date. Standard (month, day) comparison: a Feb-29 birthday is not
 * yet complete on Feb 28 of a non-leap year and IS complete on Mar 1 — the
 * documented Feb-29 convention (INV-037).
 */
export function ageAtDate(
  dobIso: string,
  onDate: { year: number; month: number; day: number },
): number | null {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(dobIso.trim());
  if (!m) return null;
  const dobYear = Number(m[1]);
  const dobMonth = Number(m[2]);
  const dobDay = Number(m[3]);
  let age = onDate.year - dobYear;
  if (onDate.month < dobMonth || (onDate.month === dobMonth && onDate.day < dobDay)) {
    age -= 1;
  }
  return age;
}

