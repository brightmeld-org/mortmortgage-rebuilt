interface DemographicFields {
  codes: [string, string, string, string, string];
  freeForm: string;
  visualObservation: string;
}

function fiveSlots(mapped: string[]): [string, string, string, string, string] {
  return [mapped[0] ?? "", mapped[1] ?? "", mapped[2] ?? "", mapped[3] ?? "", mapped[4] ?? ""];
}

/**
 * Visual-observation code (DATA-003: electronic collection, never visual
 * observation): 2 when the applicant provided the value, 3 when not provided.
 */
function visualObs(provided: boolean): string {
  return provided ? "2" : "3";
}

function ethnicityFields(demo: Record<string, unknown> | null, coApplicant: boolean, exists: boolean): DemographicFields {
  if (coApplicant && !exists) {
    return { codes: [NO_CO_APPLICANT.ethnicity, "", "", "", ""], freeForm: "", visualObservation: NO_CO_APPLICANT.visualObservation };
  }
  const values = strArray(demo?.ethnicity).map((v) => HMDA_ETHNICITY[v]).filter((c): c is string => c !== undefined);
  const provided = values.some((c) => c !== "3");
  if (values.length === 0) {
    return { codes: ["3", "", "", "", ""], freeForm: "", visualObservation: "3" };
  }
  const freeForm = str(demo?.ethnicityOtherDetail);
  return {
    codes: fiveSlots(values),
    freeForm: freeForm ? sanitizeLarText(freeForm) : "",
    visualObservation: visualObs(provided),
  };
}

interface RaceFields {
  codes: [string, string, string, string, string];
  tribeFreeForm: string;
  otherAsianFreeForm: string;
  otherPacificFreeForm: string;
  visualObservation: string;
}

function raceFields(demo: Record<string, unknown> | null, coApplicant: boolean, exists: boolean): RaceFields {
  if (coApplicant && !exists) {
    return { codes: [NO_CO_APPLICANT.race, "", "", "", ""], tribeFreeForm: "", otherAsianFreeForm: "", otherPacificFreeForm: "", visualObservation: NO_CO_APPLICANT.visualObservation };
  }
  const raw = strArray(demo?.race);
  const values = raw.map((v) => HMDA_RACE[v]).filter((c): c is string => c !== undefined);
  if (values.length === 0) {
    return { codes: ["6", "", "", "", ""], tribeFreeForm: "", otherAsianFreeForm: "", otherPacificFreeForm: "", visualObservation: "3" };
  }
  const provided = values.some((c) => c !== "6");
  // raceOtherDetails entries are assigned, in order, to the free-form slots
  // whose parent codes are selected (tribe <- 1, other Asian <- 27, other
  // Pacific Islander <- 44) — documented in the mapping artifact.
  const details = strArray(demo?.raceOtherDetails).map(sanitizeLarText);
  let detailIndex = 0;
  const takeDetail = (selected: boolean): string =>
    selected && detailIndex < details.length ? details[detailIndex++]! : "";
  const tribeFreeForm = takeDetail(values.includes("1"));
  const otherAsianFreeForm = takeDetail(values.includes("27"));
  const otherPacificFreeForm = takeDetail(values.includes("44"));
  return { codes: fiveSlots(values), tribeFreeForm, otherAsianFreeForm, otherPacificFreeForm, visualObservation: visualObs(provided) };
}

function sexFields(demo: Record<string, unknown> | null, coApplicant: boolean, exists: boolean): { code: string; visualObservation: string } {
  if (coApplicant && !exists) {
    return { code: NO_CO_APPLICANT.sex, visualObservation: NO_CO_APPLICANT.visualObservation };
  }
  const value = str(demo?.sex);
  const code = value ? HMDA_SEX[value] ?? "3" : "3";
  return { code, visualObservation: visualObs(code === "1" || code === "2") };
}

