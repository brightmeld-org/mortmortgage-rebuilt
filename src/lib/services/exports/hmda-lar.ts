function reportableWhere(year: number, timeZone: string): Prisma.ApplicationWhereInput {
  const { start, end } = larYearWindowUtc(year, timeZone);
  return {
    OR: [
      {
        workflowState: { in: ["approved", "denied", "borrower_notified"] },
        decidedAt: { gte: start, lt: end },
      },
      {
        workflowState: { in: ["withdrawn", "declined_by_borrower"] },
        stateEnteredAt: { gte: start, lt: end },
      },
    ],
  };
}

